/**
 * with-release-signing.js
 *
 * Expo config plugin that wires a REAL release signing config into
 * `android/app/build.gradle`.
 *
 * Why a plugin? `expo prebuild --clean` deletes the whole `android/` folder,
 * so any manual edit to `android/app/build.gradle` is lost. A config plugin
 * lives outside `android/` and is re-applied on every prebuild.
 *
 * Where the settings live
 * -----------------------
 * The keystore settings are kept in `<projectRoot>/keystore.properties`, i.e.
 * OUTSIDE the `android/` folder. That matters: `expo prebuild --clean` wipes
 * `android/` before the mods run, so a `android/app/keystore.properties`
 * source would simply disappear and the release build would silently fall back
 * to the debug key.
 *
 * The plugin therefore:
 *   1. reads  `<projectRoot>/keystore.properties`
 *   2. writes `android/app/keystore.properties` (storeFile relative to
 *      `android/app`, which is how Gradle's `file()` resolves it)
 *   3. patches `android/app/build.gradle` to add a `release` signing config
 *      and point the `release` build type at it.
 *
 * Run `npm run sign:android` once to create `<projectRoot>/keystore.properties`.
 */
const fs = require('fs');
const path = require('path');
const { withDangerousMod, withAppBuildGradle } = require('expo/config-plugins');

const MARKER = 'PANTRO_RELEASE_SIGNING';
const ROOT_PROPS_FILE = 'keystore.properties';

function parseProps(file) {
  if (!fs.existsSync(file)) return null;
  const props = {};
  for (const line of fs.readFileSync(file, 'utf8').split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const eq = trimmed.indexOf('=');
    if (eq === -1) continue;
    props[trimmed.slice(0, eq).trim()] = trimmed.slice(eq + 1).trim();
  }
  return props.storeFile ? props : null;
}

function readRootProps(projectRoot) {
  return parseProps(path.join(projectRoot, ROOT_PROPS_FILE));
}

/**
 * Regenerate `android/app/keystore.properties` from the root-level settings.
 * `storeFile` is stored relative to `android/app` so the Gradle build stays
 * machine independent (Gradle's `file()` resolves against the project dir).
 */
function writeAppKeystoreProps(projectRoot, props) {
  const appDir = path.join(projectRoot, 'android', 'app');
  if (!fs.existsSync(appDir)) return false;

  const storeFile = path.isAbsolute(props.storeFile)
    ? props.storeFile
    : path.resolve(projectRoot, props.storeFile);
  const relative = path.relative(appDir, storeFile).replace(/\\/g, '/');

  const contents = [
    '# Pantro Tenant - release signing (upload key for Google Play)',
    '# Generated by plugins/with-release-signing.js - do not commit.',
    `storeFile=${relative}`,
    `storePassword=${props.storePassword}`,
    `keyAlias=${props.keyAlias}`,
    `keyPassword=${props.keyPassword}`,
    '',
  ].join('\n');

  fs.writeFileSync(path.join(appDir, 'keystore.properties'), contents, 'utf8');
  return true;
}

module.exports = function withReleaseSigning(config) {
  // 1. Keep android/app/keystore.properties in sync with the root settings.
  config = withDangerousMod(config, [
    'android',
    async (cfg) => {
      const props = readRootProps(cfg.modRequest.projectRoot);
      if (!props) {
        console.log(
          '[with-release-signing] keystore.properties not found at the project root - ' +
            'release build will use the debug key. Run: npm run sign:android'
        );
        return cfg;
      }
      writeAppKeystoreProps(cfg.modRequest.projectRoot, props);
      return cfg;
    },
  ]);

  // 2. Patch the Gradle signing config.
  config = withAppBuildGradle(config, (cfg) => {
    const props = readRootProps(cfg.modRequest.projectRoot);
    if (!props) return cfg;
    if (cfg.modResults.contents.includes(MARKER)) return cfg;

    let gradle = cfg.modResults.contents;

    // 2a. Load keystore.properties at the top of the file.
    const loader = `
// ---- ${MARKER} (generated by plugins/with-release-signing.js) ----
def pantroKeystorePropertiesFile = rootProject.file('app/keystore.properties')
def pantroKeystoreProperties = new Properties()
if (pantroKeystorePropertiesFile.exists()) {
    pantroKeystoreProperties.load(new FileInputStream(pantroKeystorePropertiesFile))
}
`;
    gradle = gradle.replace(
      /^(apply plugin: "com\.android\.application")/m,
      `$1${loader}`
    );

    // 2b. Add a `release` signing config next to the generated `debug` one.
    const releaseSigning = `        release {
            storeFile file(pantroKeystoreProperties['storeFile'])
            storePassword pantroKeystoreProperties['storePassword']
            keyAlias pantroKeystoreProperties['keyAlias']
            keyPassword pantroKeystoreProperties['keyPassword']
        }
`;
    gradle = gradle.replace(
      /(signingConfigs \{\s*\n\s*debug \{[\s\S]*?\n\s*\}\n)/,
      `$1${releaseSigning}`
    );

    // 2c. Point the release build type at the real key.
    gradle = gradle.replace(
      /(buildTypes \{[\s\S]*?release \{[\s\S]*?)signingConfig signingConfigs\.debug/,
      `$1signingConfig signingConfigs.release`
    );

    cfg.modResults.contents = gradle;
    return cfg;
  });

  return config;
};
