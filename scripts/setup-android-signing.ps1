<#
    setup-android-signing.ps1
    ---------------------------------------------------------------------------
    Writes `android/app/keystore.properties` for the Pantro Tenant release
    build and verifies the key alias actually exists.

    The Play Console needs the SHA-1 of this "upload key" registered under
    Setup > App signing > Upload key certificate.

    Override the keystore location with the PANTRO_KEYSTORE env var.
#>
[CmdletBinding()]
param(
    [string]$KeyAlias = 'pantro-tenant'
)

$ErrorActionPreference = 'Stop'

$projectRoot = Split-Path -Parent $PSScriptRoot          # .../mobile_new/tenant
$repoRoot    = Resolve-Path (Join-Path $projectRoot '..\..')  # D:\Projects\pantro

# --- locate the keystore ---------------------------------------------------
$candidates = @()
if ($env:PANTRO_KEYSTORE) { $candidates += $env:PANTRO_KEYSTORE }
$candidates += (Join-Path $repoRoot 'mobile\keystore\pantro-release.keystore')
$candidates += (Join-Path $repoRoot 'keystore\pantro-release.keystore')
$candidates += (Join-Path $repoRoot 'mobile_new\keystore\pantro-release.keystore')

$keystore = $candidates | Where-Object { Test-Path $_ } | Select-Object -First 1
if (-not $keystore) {
    throw "Release keystore not found. Looked in:`n  $($candidates -join "`n  ")`nSet `$env:PANTRO_KEYSTORE to the .keystore path."
}

# --- locate keytool (JDK 17+ required by Gradle/AGP) -----------------------
$keytool = $null
if ($env:JAVA_HOME) { $keytool = Join-Path $env:JAVA_HOME 'bin\keytool.exe' }
if (-not $keytool -or -not (Test-Path $keytool)) {
    $keytool = (Get-Command keytool.exe -ErrorAction SilentlyContinue).Source
}
if (-not $keytool) {
    $jdk = Get-ChildItem 'C:\Program Files\Eclipse Adoptium' -Directory -ErrorAction SilentlyContinue |
           Sort-Object Name -Descending | Select-Object -First 1
    if ($jdk) { $keytool = Join-Path $jdk.FullName 'bin\keytool.exe' }
}
if (-not $keytool -or -not (Test-Path $keytool)) { throw 'keytool.exe not found - install a JDK 17+ and set JAVA_HOME.' }

# --- read the store password ----------------------------------------------
# It is stored next to the owner app's keystore.properties.
$ownerProps = Join-Path $repoRoot 'mobile\owner-app\android\app\keystore.properties'
$storePassword = $null
$keyPassword   = $null
if (Test-Path $ownerProps) {
    foreach ($line in Get-Content $ownerProps) {
        if ($line -match '^\s*storePassword\s*=\s*(.+)$') { $storePassword = $Matches[1].Trim() }
        if ($line -match '^\s*keyPassword\s*=\s*(.+)$')   { $keyPassword   = $Matches[1].Trim() }
    }
}
if (-not $storePassword) { throw "Could not read the keystore password from $ownerProps" }
if (-not $keyPassword) { $keyPassword = $storePassword }

# --- verify the alias exists ----------------------------------------------
$listing = @(& $keytool -list -keystore $keystore -storepass $storePassword 2>&1)
if ($LASTEXITCODE -ne 0) { throw "keytool could not open the keystore:`n$($listing -join "`n")" }

# keytool prints either "Alias name: <alias>" (verbose) or "<alias>, <date>, ..." (summary)
$aliasPattern = $KeyAlias -replace '([.*+?^${}()|\[\]\\])', '\$1'
$hasAlias = $false
$aliasNames = @()
foreach ($line in $listing) {
    $text = "$line"
    if ($text -match "Alias name:\s*(\S+)") { $aliasNames += $Matches[1] }
    elseif ($text -match '^\s*([A-Za-z0-9_.\-]+)\s*,') { $aliasNames += $Matches[1] }
    if ($text -match "Alias name:\s*$aliasPattern(\s|$)" -or $text -match "^\s*$aliasPattern\s*,") {
        $hasAlias = $true
    }
}
if (-not $hasAlias) {
    throw ("Alias '{0}' not found in {1}. Available aliases: {2}" -f $KeyAlias, $keystore, ($aliasNames -join ', '))
}

# --- write android/app/keystore.properties --------------------------------
$appDir = Join-Path $projectRoot 'android\app'
if (-not (Test-Path $appDir)) { throw "android/app not found - run 'npx expo prebuild --platform android' first." }

# Path relative to android/app (Gradle's `file()` resolves against the project dir).
$keystoreFull = (Resolve-Path $keystore).Path
$fromUri = New-Object System.Uri(($appDir.TrimEnd('\') + '\'))
$toUri   = New-Object System.Uri($keystoreFull)
$relative = [System.Uri]::UnescapeDataString($fromUri.MakeRelativeUri($toUri).ToString()).Replace('\', '/')

$props = @(
    '# Pantro Tenant - release signing (upload key for Google Play)'
    "# Generated by scripts/setup-android-signing.ps1 - do not commit."
    "storeFile=$relative"
    "storePassword=$storePassword"
    "keyAlias=$KeyAlias"
    "keyPassword=$keyPassword"
)
$propsFile = Join-Path $appDir 'keystore.properties'
Set-Content -Path $propsFile -Value $props -Encoding UTF8

# --- also keep a copy OUTSIDE android/ --------------------------------------
# `expo prebuild --clean` deletes the whole android/ folder, which would
# delete android/app/keystore.properties before plugins/with-release-signing.js
# gets a chance to read it - the release build would then silently fall back to
# the debug key. The project-root copy survives and is the source of truth.
$rootFromUri = New-Object System.Uri(($projectRoot.TrimEnd('\') + '\'))
$rootToUri   = New-Object System.Uri($keystoreFull)
$rootRelative = [System.Uri]::UnescapeDataString($rootFromUri.MakeRelativeUri($rootToUri).ToString()).Replace('\', '/')
$rootProps = @(
    '# Pantro Tenant - release signing (upload key for Google Play)'
    '# Source of truth for plugins/with-release-signing.js - do not commit.'
    "storeFile=$rootRelative"
    "storePassword=$storePassword"
    "keyAlias=$KeyAlias"
    "keyPassword=$keyPassword"
)
$rootPropsFile = Join-Path $projectRoot 'keystore.properties'
Set-Content -Path $rootPropsFile -Value $rootProps -Encoding UTF8

Write-Host ''
Write-Host 'Release signing configured.' -ForegroundColor Green
Write-Host "  keystore : $keystore"
Write-Host "  alias    : $KeyAlias"
Write-Host "  props    : $propsFile"
Write-Host "  source   : $rootPropsFile  (survives 'expo prebuild --clean')"
Write-Host ''
Write-Host 'Upload key fingerprints (register the SHA-1 in Play Console):' -ForegroundColor Yellow
& $keytool -list -v -keystore $keystore -storepass $storePassword -alias $KeyAlias 2>&1 |
    Select-String -Pattern 'SHA1:|SHA256:' | ForEach-Object { "  $($_.ToString().Trim())" }
Write-Host ''
